def audit_content(niche: str, audience: str, product: str) -> dict:
    """
    Возвращает рекомендации по контенту на основе введённой ниши.
    Если ниша неизвестна — использует общий набор.
    """
    niche = niche.strip().lower()
    data = NICHE_MAP.get(niche, NICHE_MAP["студенты"])

    # Перемешиваем, чтобы при повторных запросах были разные варианты
    topics = data["topics"][:]
    random.shuffle(topics)
    lsi = data["lsi"][:]
    random.shuffle(lsi)
    formats = data["formats"][:]
    random.shuffle(formats)

    return {
        "niche": niche,
        "audience": audience.strip(),
        "product": product.strip(),
        "recommended_topics": topics[:3],
        "lsi_terms": lsi[:5],
        "formats": formats[:2],
        "angle": data["angle"],
        "gap": data["gap"]
    }
