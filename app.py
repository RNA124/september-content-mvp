@app.route("/audit", methods=["POST"])
def audit():
    data = request.get_json()
    niche = data.get("niche", "").strip()
    audience = data.get("audience", "").strip()
    product = data.get("product", "").strip()

    if not niche or len(niche) > 80:
        return jsonify({"error": "Укажи нишу (1–80 символов)"}), 400
    if not audience or len(audience) > 80:
        return jsonify({"error": "Укажи аудиторию (1–80 символов)"}), 400

    result = audit_content(niche, audience, product)
    return jsonify(result)


@app.route("/generate", methods=["POST"])
def generate():
    data = request.get_json()
    mascot_key = data.get("mascot", "alisa")
    topic = data.get("topic", "").strip()
    lsi_terms = data.get("lsi_terms", [])

    if mascot_key not in MASCOTS:
        return jsonify({"error": "Неизвестный маскот"}), 400
    if not topic or len(topic) > 120:
        return jsonify({"error": "Тема должна быть от 1 до 120 символов"}), 400

    result = generate_post(mascot_key, topic, lsi_terms)
    return jsonify(result)


